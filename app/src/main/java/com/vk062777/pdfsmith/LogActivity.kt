package com.vk062777.pdfsmith

import android.os.Build
import android.os.Bundle
import android.view.Gravity
import android.widget.LinearLayout
import android.widget.TextView
import com.vk062777.pdfsmith.databinding.ActivityLogBinding
import com.vk062777.pdfsmith.engine.PdfEngine
import com.vk062777.pdfsmith.util.AppLog
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/** What the app has done, when, and a PDF export of the lot. */
class LogActivity : PdfActivity() {

    private lateinit var binding: ActivityLogBinding

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        binding = ActivityLogBinding.inflate(layoutInflater)
        setContentView(binding.root)
        binding.toolbar.setNavigationOnClickListener { finish() }
        binding.btnExport.setOnClickListener { exportPdf() }
        binding.btnClear.setOnClickListener { confirmClear() }
        render()
    }

    override fun onResume() {
        super.onResume()
        if (::binding.isInitialized) render()
    }

    private fun render() {
        val list = binding.list
        list.removeAllViews()
        val entries = AppLog.entries(this).reversed()      // newest first
        binding.btnExport.isEnabled = entries.isNotEmpty()
        binding.btnClear.isEnabled = entries.isNotEmpty()
        if (entries.isEmpty()) {
            list.addView(TextView(this).apply {
                text = getString(R.string.log_empty)
                setTextColor(getColor(R.color.text_secondary))
                textSize = 14f
                gravity = Gravity.CENTER
                setPadding(0, dp(28), 0, 0)
            })
            return
        }
        for (e in entries) {
            list.addView(TextView(this).apply {
                text = AppLog.format(e)
                setTextColor(getColor(if (e.ok) R.color.text_primary else R.color.danger))
                textSize = 12.5f
                typeface = android.graphics.Typeface.MONOSPACE
                setPadding(dp(6), dp(7), dp(6), dp(7))
                layoutParams = LinearLayout.LayoutParams(
                    LinearLayout.LayoutParams.MATCH_PARENT,
                    LinearLayout.LayoutParams.WRAP_CONTENT
                )
            })
        }
    }

    /** The export carries everything a log file should: what, when, and where it ran. */
    private fun exportPdf() {
        val entries = AppLog.entries(this)                 // oldest first
        if (entries.isEmpty()) return toast(getString(R.string.log_empty))
        val fmt = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US)

        val facts = listOf(
            arrayOf("Application", "KavoPDF"),
            arrayOf("Version", "${versionName()}  (build ${versionCode()})"),
            arrayOf("Package", packageName),
            arrayOf("Device", "${Build.MANUFACTURER} ${Build.MODEL}"),
            arrayOf("Android", "${Build.VERSION.RELEASE}  (API ${Build.VERSION.SDK_INT})"),
            arrayOf("Generated", fmt.format(Date())),
            arrayOf("Entries", entries.size.toString())
        )
        val columns = listOf(
            PdfEngine.Column("TIME", 1.6f),
            PdfEngine.Column("RESULT", 0.7f),
            PdfEngine.Column("TASK", 1.4f),
            PdfEngine.Column("OUTPUT", 2.3f)
        )
        val rows = entries.map {
            arrayOf(fmt.format(Date(it.time)), if (it.ok) "OK" else "FAIL", it.action, it.detail)
        }
        val accent = accentColour()
        runAndSave("kavopdf-activity-log.pdf") { out ->
            PdfEngine.report(
                out, "KAVOPDF", getString(R.string.log_report_title),
                "Activity on this device", facts, columns, rows,
                "Generated by KavoPDF. Passwords are never recorded.", accent
            )
        }
    }

    /** The current theme's primary colour, so the report matches the app. */
    private fun accentColour(): Int {
        val tv = android.util.TypedValue()
        val resolved = theme.resolveAttribute(
            com.google.android.material.R.attr.colorPrimary, tv, true
        )
        return if (resolved && tv.data != 0) tv.data else 0xFF3B5BDB.toInt()
    }

    private fun confirmClear() {
        androidx.appcompat.app.AlertDialog.Builder(this)
            .setTitle(R.string.tool_log)
            .setMessage(R.string.log_confirm_clear)
            .setPositiveButton(R.string.log_clear) { _, _ ->
                AppLog.clear(this); toast(getString(R.string.log_cleared)); render()
            }
            .setNegativeButton(R.string.action_cancel, null)
            .show()
    }

    private fun versionName(): String = try {
        packageManager.getPackageInfo(packageName, 0).versionName ?: "?"
    } catch (_: Exception) { "?" }

    private fun versionCode(): Long = try {
        val pi = packageManager.getPackageInfo(packageName, 0)
        if (Build.VERSION.SDK_INT >= 28) pi.longVersionCode else pi.versionCode.toLong()
    } catch (_: Exception) { 0L }

    private fun dp(v: Int): Int = (v * resources.displayMetrics.density).toInt()
}
